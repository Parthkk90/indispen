import { instructions } from '@1inch/swap-vm-sdk'
import type { IArgsData, Opcode } from './opcode'

const { EMPTY_OPCODE, controls, xycSwap } = instructions
import { indexNavGuardXD } from './instructions/index-nav-guard'
import { indexNavPriceAdjusterXD } from './instructions/index-nav-price-adjuster'
import { indexInventorySkewXD } from './instructions/index-inventory-skew'
import { indexMaxTradeXD } from './instructions/index-max-trade'
import { indexCapabilityGuardXD } from './instructions/index-capability-guard'

/**
 * AquaIndexSwapVMRouter instruction set, version 1.
 *
 * The published `@1inch/swap-vm-sdk` tables are position-indexed for the v1.0 router layout, whereas the router built
 * from swap-vm `main` (and therefore AquaIndexSwapVMRouter) uses the banked `OpcodeList` numbering. This table is
 * therefore SPARSE: the array index is exactly the Solidity opcode byte, unused slots are `EMPTY_OPCODE` and are
 * rejected on decode. Equality with Solidity is asserted against `test/golden.json` (generated by Foundry).
 *
 * Upstream instructions on the router but NOT exposed here (arg coders not verified against `main`):
 * Jump(0x03) JumpIfTokenIn(0x31) JumpIfTokenOut(0x32) XYCConcentrateSwap(0x51) FeeFlatIn(0x70).
 */
export const INSTRUCTION_SET_VERSION = 1

export const OPCODE_IDS = {
  Salt: 0x02,
  Deadline: 0x20,
  XYCSwap: 0x50,
  IndexNavGuard: 0xe0,
  IndexNavPriceAdjuster: 0xe1,
  IndexInventorySkew: 0xe2,
  IndexMaxTrade: 0xe3,
  IndexCapabilityGuard: 0xe4
} as const

function buildSet(): Opcode<IArgsData>[] {
  const set = new Array<Opcode<IArgsData>>(256).fill(EMPTY_OPCODE as Opcode<IArgsData>)
  const put = (id: number, op: unknown) => {
    if (set[id] !== (EMPTY_OPCODE as unknown)) throw new Error(`opcode slot 0x${id.toString(16)} already assigned`)
    set[id] = op as Opcode<IArgsData>
  }
  put(OPCODE_IDS.Salt, controls.salt)
  put(OPCODE_IDS.Deadline, controls.deadline)
  put(OPCODE_IDS.XYCSwap, xycSwap.xycSwapXD)
  put(OPCODE_IDS.IndexNavGuard, indexNavGuardXD)
  put(OPCODE_IDS.IndexNavPriceAdjuster, indexNavPriceAdjusterXD)
  put(OPCODE_IDS.IndexInventorySkew, indexInventorySkewXD)
  put(OPCODE_IDS.IndexMaxTrade, indexMaxTradeXD)
  put(OPCODE_IDS.IndexCapabilityGuard, indexCapabilityGuardXD)
  return set
}

export const aquaIndexInstructions: Opcode<IArgsData>[] = buildSet()

export function opcodeByte(op: unknown): number {
  const i = aquaIndexInstructions.indexOf(op as Opcode<IArgsData>)
  if (i < 0 || (op as unknown) === EMPTY_OPCODE) throw new Error('opcode is not part of the AquaIndex instruction set')
  return i
}
